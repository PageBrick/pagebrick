// Builds core/assets/editor.js (the panel's rich text editor) from src/editor.js, and core/assets/editor.LICENSE.txt with the
// licences of everything bundled in it. Run `npm install` once, then `npm run build`. Sites never run this: the result is committed.
import {build} from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const assets = path.resolve(here, '../../core/assets');
const modules = path.join(here, 'node_modules');

// The toolbar's icons (Lucide, ISC) are read from the package and inlined as the inside of each <svg>.
const icons = {};
for (const name of ['bold', 'italic', 'underline', 'strikethrough', 'heading-2', 'heading-3', 'list', 'list-ordered', 'quote', 'link', 'unlink',
    'image', 'table', 'minus', 'undo-2', 'redo-2', 'trash-2', 'x', 'check']) {
    const svg = fs.readFileSync(path.join(modules, 'lucide-static/icons', name + '.svg'), 'utf8');
    icons[name] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').replace(/> </g, '><').trim();
}

const result = await build({
    entryPoints: [path.join(here, 'src/editor.js')],
    outfile: path.join(assets, 'editor.js'),
    bundle: true,
    minify: true,
    format: 'iife',
    target: ['es2020'],
    legalComments: 'none',
    define: {__ICONS__: JSON.stringify(icons)},
    banner: {js: '/* PageBrick rich text editor. TipTap and ProseMirror (MIT), icons from Lucide (ISC): see editor.LICENSE.txt. Source: tools/editor. */'},
    metafile: true,
    logLevel: 'warning',
});

// The licence text of every package that ended up in the bundle (the same text is written once).
const packages = new Set();
for (const file of Object.keys(result.metafile.inputs)) {
    const match = file.split(path.sep).join('/').match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
    if (match) packages.add(match[1]);
}
packages.add('lucide-static');
const byText = new Map();
for (const name of [...packages].sort()) {
    const dir = path.join(modules, name);
    const info = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const file = fs.readdirSync(dir).find((f) => /^licen[sc]e(\.(md|txt))?$/i.test(f));
    const text = file ? fs.readFileSync(path.join(dir, file), 'utf8').trim() : `(no licence file in the package; declared licence: ${info.license})`;
    if (!byText.has(text)) byText.set(text, []);
    byText.get(text).push(`${name} ${info.version}`);
}
const out = ['Licences of what is bundled in editor.js (generated by tools/editor/build.mjs; do not edit).', ''];
for (const [text, names] of byText) out.push('='.repeat(78), names.join('\n'), '='.repeat(78), '', text, '');
fs.writeFileSync(path.join(assets, 'editor.LICENSE.txt'), out.join('\n'));

const size = fs.statSync(path.join(assets, 'editor.js')).size;
console.log(`editor.js ${(size / 1024).toFixed(0)} KB, ${packages.size} packages`);
